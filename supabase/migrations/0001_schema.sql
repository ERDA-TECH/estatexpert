-- ---------- helper functions ----------
create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = ''
as $$ select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin') $$;

create or replace function public.haversine_km(lat1 numeric, lng1 numeric, lat2 numeric, lng2 numeric) returns numeric
language sql immutable
as $$
  select round((6371 * 2 * asin(sqrt(
    power(sin(radians(lat2 - lat1) / 2), 2) +
    cos(radians(lat1)) * cos(radians(lat2)) * power(sin(radians(lng2 - lng1) / 2), 2)
  )))::numeric, 1)
$$;

create or replace function public.set_updated_at() returns trigger
language plpgsql as $$ begin new.updated_at = now(); return new; end $$;
create trigger properties_updated_at before update on properties
  for each row execute function public.set_updated_at();

-- A profile row is created automatically for every new sign-up.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name, phone)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', split_part(coalesce(new.email,''), '@', 1)), new.phone)
  on conflict (id) do nothing;
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Nobody can promote themselves to admin.
create or replace function public.protect_role() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if new.role is distinct from old.role and auth.uid() is not null and not public.is_admin() then
    raise exception 'Only an admin can change a role';
  end if;
  return new;
end $$;
create trigger profiles_protect_role before update on profiles
  for each row execute function public.protect_role();

-- Sellers can submit and edit pending listings. Only an admin can publish, reject or verify.
-- Calls without a user (the service role used by seed scripts and server jobs) are not restricted.
create or replace function public.guard_property() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if auth.uid() is null or public.is_admin() then
    if tg_op = 'UPDATE' and new.status = 'live' and old.status <> 'live' and new.published_at is null then
      new.published_at = now();
    end if;
    return new;
  end if;
  if tg_op = 'INSERT' then
    new.status = 'pending';
    new.verified = false;
    new.published_at = null;
    new.owner_id = auth.uid();
  else
    if new.status is distinct from old.status and not (old.status = 'rejected' and new.status = 'pending') then
      raise exception 'Only an admin can change the listing status';
    end if;
    if new.verified is distinct from old.verified or new.published_at is distinct from old.published_at or new.owner_id is distinct from old.owner_id then
      raise exception 'Only an admin can change verification or ownership';
    end if;
  end if;
  return new;
end $$;
create trigger properties_guard before insert or update on properties
  for each row execute function public.guard_property();

-- Sellers can attach papers but cannot mark them verified.
create or replace function public.guard_document() returns trigger
language plpgsql security definer set search_path = ''
as $$
begin
  if auth.uid() is not null and not public.is_admin() then
    if tg_op = 'INSERT' then new.status = 'pending';
    elsif new.status is distinct from old.status then raise exception 'Only an admin can verify a document';
    end if;
  end if;
  return new;
end $$;
create trigger documents_guard before insert or update on property_documents
  for each row execute function public.guard_document();

