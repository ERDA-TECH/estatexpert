-- Reference data: everyone reads, only admins write.
create policy states_read on states for select using (true);
create policy cities_read on cities for select using (true);
create policy localities_read on localities for select using (true);
create policy nearby_read on nearby_places for select using (true);
create policy states_admin on states for all using (public.is_admin()) with check (public.is_admin());
create policy cities_admin on cities for all using (public.is_admin()) with check (public.is_admin());
create policy localities_admin on localities for all using (public.is_admin()) with check (public.is_admin());
create policy nearby_admin on nearby_places for all using (public.is_admin()) with check (public.is_admin());

-- Profiles: you see and edit your own, admins see all.
create policy profiles_select on profiles for select using (id = auth.uid() or public.is_admin());
create policy profiles_update on profiles for update using (id = auth.uid() or public.is_admin()) with check (id = auth.uid() or public.is_admin());

-- Properties: the public sees live listings, owners see their own, admins see everything.
create policy properties_select on properties for select
  using (status = 'live' or owner_id = auth.uid() or public.is_admin());
create policy properties_insert on properties for insert to authenticated
  with check (owner_id = auth.uid() or public.is_admin());
create policy properties_update on properties for update to authenticated
  using ((owner_id = auth.uid() and status in ('draft','pending','rejected')) or public.is_admin())
  with check (owner_id = auth.uid() or public.is_admin());
create policy properties_delete on properties for delete to authenticated
  using ((owner_id = auth.uid() and status in ('draft','pending','rejected')) or public.is_admin());

-- Seller contact details: owner and admin only.
create policy private_all on property_private for all to authenticated
  using (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()))
  with check (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()));

-- Documents and media follow the visibility of their property.
create policy documents_select on property_documents for select
  using (public.is_admin() or exists (select 1 from properties p where p.id = property_id and (p.status = 'live' or p.owner_id = auth.uid())));
create policy documents_write on property_documents for all to authenticated
  using (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()))
  with check (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()));
create policy media_select on property_media for select
  using (public.is_admin() or exists (select 1 from properties p where p.id = property_id and (p.status = 'live' or p.owner_id = auth.uid())));
create policy media_write on property_media for all to authenticated
  using (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()))
  with check (public.is_admin() or exists (select 1 from properties p where p.id = property_id and p.owner_id = auth.uid()));

-- Enquiries: anyone can send one for a live listing. Buyers read their own. Only admins work the pipeline.
create policy enquiries_insert on enquiries for insert to anon, authenticated
  with check ((user_id is null or user_id = auth.uid())
    and exists (select 1 from properties p where p.id = property_id and p.status = 'live'));
create policy enquiries_select on enquiries for select to authenticated
  using (user_id = auth.uid() or public.is_admin());
create policy enquiries_update on enquiries for update to authenticated
  using (public.is_admin()) with check (public.is_admin());

create policy saved_all on saved_properties for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
create policy alerts_all on alerts for all to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

