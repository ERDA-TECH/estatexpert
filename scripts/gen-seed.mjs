// Generates supabase/seed.sql from the sample data in lib/seed.js.
// Run: node scripts/gen-seed.mjs
import {writeFileSync} from 'node:fs';
import {STATES,CITIES,AREAS,DOCS,SEED,SEED_QUEUE,SEED_LEADS,nearby} from '../lib/seed.js';

const q=v=>v==null?'null':"'"+String(v).replace(/'/g,"''")+"'";
const n=v=>v==null||Number.isNaN(v)?'null':String(v);
const arr=a=>'array['+a.map(q).join(',')+']::text[]';
const DOC_STATUS=['pending','verified','not_applicable'];
const out=[];
out.push('-- Generated by scripts/gen-seed.mjs from lib/seed.js. All names, prices and distances are sample data.');
out.push('begin;');

for(const [code,s] of Object.entries(STATES))
  out.push(`insert into states (code,name,short_name,rera_authority,land_record_name,registration_note) values (${q(code)},${q(s.n)},${q(s.short)},${q(s.rera)},${q(s.land)},${q(s.reg)});`);

for(const [id,c] of Object.entries(CITIES))
  out.push(`insert into cities (id,name,state_code,has_metro,it_hub,airport,lat,lng) values (${q(id)},${q(c.n)},${q(c.s)},${c.metro},${q(c.it)},${q(c.airport)},${n(c.ll[0])},${n(c.ll[1])});`);

for(const [id,a] of Object.entries(AREAS)){
  const d=a.d;
  out.push(`insert into localities (id,city_id,name,blurb,map_x,map_y,school_km,hospital_km,transit_km,it_km,mall_km,airport_km) values (${q(id)},${q(a.c)},${q(a.n)},${q(a.blurb)},${a.x},${a.y},${d.join(',')});`);
  for(const nb of nearby(id))
    out.push(`insert into nearby_places (locality_id,category,name,distance_km,drive_minutes) values (${q(id)},${q(nb.k)},${q(nb.name)},${nb.km},${nb.min});`);
}

const all=[...SEED,...SEED_QUEUE.map((p,i)=>({...p,id:String(101+i)}))];
for(const p of all){
  const land=p.type==='Plot'||p.type==='Farm land';
  const live=p.status==='Live';
  out.push(`insert into properties (id,title,type,locality_id,beds,baths,built_up_sqft,plot_size_sqyd,acres,price_inr,facing,floor_label,age_years,furnishing,parking,approval_authority,rera_number,loan_available,nri_eligible,description,amenities,status,verified,hue,published_at) values (${p.id},${q(p.title)},${q(p.type)},${q(p.area)},${p.beds||0},${p.baths||0},${land?'null':n(p.sqft)},${p.sqyd||0},${n(p.acres)},${p.price},${q(p.facing)},${q(p.floor||null)},${p.age||0},${q(p.furn)},${p.parking||0},${q(p.approval)},${q(p.rera||null)},${p.loan},${p.nri},${q(p.desc)},${arr(p.amen||[])},${live?"'live'":"'pending'"},${p.verified&&live},${p.hue||200},${live?`now() - interval '${p.posted||0} days'`:'null'});`);
  for(const [k] of DOCS)
    out.push(`insert into property_documents (property_id,doc_key,status) values (${p.id},${q(k)},${q(DOC_STATUS[p.docs[k]])});`);
}
out.push("select setval(pg_get_serial_sequence('properties','id'), (select max(id) from properties));");

const LS={'New':'new','Contacted':'contacted','Visit scheduled':'visit_scheduled','Closed':'closed'};
const ago=['2 hours','1 day','2 days','7 days','3 hours','1 day'];
SEED_LEADS.forEach((l,i)=>{
  out.push(`insert into enquiries (property_id,name,email,time_zone,kind,preferred_contact,message,status,created_at) values (${l.prop},${q(l.name)},'sample@example.com',${q(l.loc)},${l.kind==='Video call'?"'video_call'":"'enquiry'"},'WhatsApp',${q(l.note)},${q(LS[l.status])},now() - interval '${ago[i]||'1 day'}');`);
});
out.push('commit;');
writeFileSync(new URL('../supabase/seed.sql',import.meta.url),out.join('\n')+'\n');
console.log('seed.sql written:',out.length,'statements');
